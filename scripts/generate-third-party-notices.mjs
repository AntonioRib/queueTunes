import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const projects = process.argv.slice(2).filter((arg) => arg !== '--check');
if (projects.some((project) => !['frontend', 'backend'].includes(project))) {
  throw new Error('Expected frontend and/or backend, with optional --check');
}

for (const project of projects.length ? projects : ['frontend', 'backend']) {
  const lock = JSON.parse(readFileSync(resolve(root, project, 'package-lock.json'), 'utf8'));
  const sections = [
    'QueueTunes third-party runtime dependency notices',
    'Generated by scripts/generate-third-party-notices.mjs from the lockfile and installed packages.',
    'Includes all production dependencies, even when a browser build does not bundle every package.',
    'Build/test tools are not redistributed here; retain their own notices if redistributing them.',
    `\nQueueTunes original code and favicon:\n${readFileSync(resolve(root, 'LICENSE'), 'utf8').trim()}`,
  ];
  for (const [path, entry] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b, 'en'))) {
    if (!path || entry.dev) continue;
    const directory = resolve(root, project, path);
    const pkg = JSON.parse(readFileSync(resolve(directory, 'package.json'), 'utf8'));
    if (pkg.version !== entry.version) throw new Error(`Run npm ci: ${project}/${path} is stale`);
    const names = readdirSync(directory).sort();
    const documents = names
      .filter((name) => /(^|[-_.])(licen[cs]e|copying|notice)([-_.]|$)/i.test(name))
      .filter((name) => statSync(resolve(directory, name)).isFile())
      .map((name) => `${name}\n${readFileSync(resolve(directory, name), 'utf8').trim()}`);
    if (!documents.length) {
      const readme = names.find((name) => /^readme(?:\.md)?$/i.test(name));
      const text = readme ? readFileSync(resolve(directory, readme), 'utf8') : '';
      const license = text.match(/(?:^|\n)(?:#{1,3} License[^\n]*|License\n-+)\s*\n([\s\S]*)/i);
      if (license && /Permission is hereby granted/.test(license[1])) {
        documents.push(`${readme} (license section)\n${license[1].trim()}`);
      } else if (pkg.name === 'react-secure-storage' && pkg.version === '1.3.2') {
        documents.push(readFileSync(resolve(root, 'licenses/react-secure-storage-1.3.2.txt'), 'utf8').trim());
      }
    }
    if (!documents.length) throw new Error(`Missing license text: ${project}/${path}`);
    sections.push(`\n${'='.repeat(72)}\n${pkg.name}@${pkg.version}\nLicense: ${pkg.license}\n\n${documents.join('\n\n')}`);
  }
  const output = resolve(root, project, project === 'frontend' ? 'public/third-party-notices.txt' : 'THIRD_PARTY_NOTICES.txt');
  const content = `${sections.join('\n')}\n`.replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, '');
  if (check) {
    if (readFileSync(output, 'utf8') !== content) throw new Error(`Stale notices: ${output}`);
  } else {
    writeFileSync(output, content);
  }
  console.log(`${check ? 'Verified' : 'Generated'} ${project} runtime notices`);
}
